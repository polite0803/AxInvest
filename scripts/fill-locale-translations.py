# 排除规则：这些值不需要翻译（纯英文/数字/技术术语等）
SKIP_PATTERNS = [
    r'^[A-Za-z0-9\s\-\_\.\,\:\;\/\(\)\[\]\{\}\<\>\=\+\*\!@#\$%\^&\|\~\`\'\"\\]+$',  # 纯 ASCII
    r'^https?://',  # URL
    r'^\d+$',  # 纯数字
    r'^\d+[\.\,]\d+$',  # 小数
    r'^(\d+[smhdw]?)+$',  # 时间单位
    r'^(HTTP|HTTPS|JSON|YAML|XML|HTML|CSS|JS|TS|SQL|API|URL|URI|UUID|ID|GPU|CPU|RAM|SSD|HDD|WAL|MCP|RL|RLHF|PPO|DPO|GRPO|SPDX|AGPL|MIT|GPL|BSD|ASF|NPM|PNPM|CJS|MJS|JSX|TSX|VUE|RUST|TOML|INI|CFG|MD|TXT|PNG|JPG|JPEG|GIF|SVG|WEBP|ICO)$',
    r'^(Cron|unix|epoch|Token|Top P|Top K|Sharpe|Sortino|Calmar|Omega|Rhai|ECharts|React|TypeScript|Rust|AxAgent|AxInvest|OpenAI|Anthropic|Claude|GPT|Gemini|Serenity|SeaORM|Tokio|Tauri|Electron|Vite|Vitest|Playwright|Monaco|Codex|Cursor|Copilot|ChatGPT|Ollama|Hermes)$',
    r'^(llm|LLM|mcp|MCP)$',
    r'^[-+]?\d+(\.\d+)?[%°]?$',  # 带单位的数字
]


def should_skip(value):
    """判断值是否需要跳过翻译"""
    if not isinstance(value, str):
        return True
    if value.strip() == "":
        return True
    for pat in SKIP_PATTERNS:
        if re.fullmatch(pat, value.strip()):
            return True
    return False


def apply_zh_tw(value):
    """对中文值做简→繁转换"""
    # 先尝试整词匹配
    if value in S2T_WORDS:
        return S2T_WORDS[value]

    # 逐字替换
    result = []
    for ch in value:
        if ch in S2T_CHARS:
            result.append(S2T_CHARS[ch])
        else:
            result.append(ch)
    return "".join(result)


def apply_ja(value):
    """对中文值做日文转换"""
    if value in JA_WORDS:
        return JA_WORDS[value]

    # 保守策略：如果不在词汇表中，返回原值
    return value


def extract_all_values(data, prefix=""):
    """递归提取所有叶节点路径和值"""
    result = {}
    for key, value in data.items():
        path = f"{prefix}.{key}" if prefix else key
        if isinstance(value, dict):
            result.update(extract_all_values(value, path))
        else:
            result[path] = value
    return result


def find_untranslated(zh_cn_values, target_values):
    """找出 target 中与 zh-CN 值相同的 key"""
    untranslated = {}
    for key, zh_val in zh_cn_values.items():
        if key in target_values:
            tv = target_values[key]
            if isinstance(tv, str) and tv == zh_val and not should_skip(zh_val):
                untranslated[key] = (zh_val, tv)
    return untranslated


def main():
    with open(os.path.join(LOCALES_DIR, "zh-CN.json"), "r", encoding="utf-8") as f:
        zh_cn = json.load(f)
    zh_cn_flat = extract_all_values(zh_cn)

    for lang in ["zh-TW", "ja"]:
        filepath = os.path.join(LOCALES_DIR, f"{lang}.json")
        with open(filepath, "r", encoding="utf-8") as f:
            data = json.load(f)

        target_flat = extract_all_values(data)
        untranslated = find_untranslated(zh_cn_flat, target_flat)
        print(f"[{lang}] 找到 {len(untranslated)} 个完全相同的翻译")

        if not untranslated:
            continue

        apply_fn = apply_zh_tw if lang == "zh-TW" else apply_ja
        updated = 0
        skipped = 0

        for key_path, (zh_val, _) in untranslated.items():
            new_val = apply_fn(zh_val)
            if new_val != zh_val:
                # 递归定位并设置
                keys = key_path.split(".")
                d = data
                for k in keys[:-1]:
                    d = d[k]
                d[keys[-1]] = new_val
                updated += 1
            else:
                skipped += 1

        if updated > 0:
            with open(filepath, "w", encoding="utf-8") as f:
                json.dump(data, f, ensure_ascii=False, indent=2)
                f.write("\n")
            print(f"[{lang}] 已更新 {updated} 个翻译值，{skipped} 个无映射跳过")
        else:
            print(f"[{lang}] 所有相同值均无可用翻译映射")


if __name__ == "__main__":
    main()
